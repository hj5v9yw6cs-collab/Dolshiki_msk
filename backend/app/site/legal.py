"""Тексты политики обработки ПДн и согласия.

Это ЧЕРНОВИК, собранный по типовой структуре. Перед публикацией текст
обязан вычитать юрист и вписать реальные реквизиты оператора: без этого
документ не выполняет свою функцию, а создаёт её видимость.

Реквизиты подставляются из content/site.json, чтобы не править их в коде.
"""

from __future__ import annotations

from html import escape

from .content import Content

REVIEW_BANNER = (
    '<div class="notice notice--warn"><b>Черновик.</b> Текст составлен по типовой '
    "структуре и требует проверки юристом: нужно вписать реальные реквизиты "
    "оператора, сроки хранения и порядок обращения. До проверки не публикуйте "
    "сайт для клиентов.</div>"
)


def _operator(data: Content) -> str:
    company = data.company
    return (
        f"<p><b>Оператор персональных данных:</b> {escape(company.get('legal_name', ''))}, "
        f"ИНН {escape(str(company.get('inn', '')))}, адрес: {escape(company.get('address', ''))}. "
        f"Контакты: {escape(company.get('phone', ''))}, "
        f"<a href=\"mailto:{escape(company.get('email', ''))}\">{escape(company.get('email', ''))}</a>.</p>"
    )


def policy_html(data: Content) -> str:
    return REVIEW_BANNER + _operator(data) + """
<h2>1. Общие положения</h2>
<p>Настоящая политика определяет порядок обработки персональных данных
посетителей сайта и клиентов оператора и меры по обеспечению их безопасности.
Политика разработана в соответствии с Федеральным законом от 27.07.2006
№ 152-ФЗ «О персональных данных».</p>

<h2>2. Какие данные обрабатываются</h2>
<p>При обращении через сайт: имя, номер телефона, адрес электронной почты,
название объекта строительства, сведения, которые посетитель сообщает
добровольно в комментарии, а также данные о введённых параметрах расчёта.</p>
<p>При заключении договора и ведении дела дополнительно: паспортные данные,
сведения о договоре участия в долевом строительстве, платёжные документы,
сведения о судебном производстве.</p>

<h2>3. Цели обработки</h2>
<ul>
<li>Ответ на обращение и консультирование.</li>
<li>Заключение и исполнение договора об оказании юридических услуг.</li>
<li>Представление интересов клиента в отношениях с застройщиком и в суде.</li>
<li>Исполнение требований законодательства.</li>
</ul>

<h2>4. Правовые основания</h2>
<p>Согласие субъекта персональных данных, договор, стороной которого является
субъект, а также требования законодательства Российской Федерации.</p>

<h2>5. Где хранятся данные</h2>
<p>Базы данных, содержащие персональные данные граждан Российской Федерации,
расположены на территории Российской Федерации.</p>

<h2>6. Как обеспечивается безопасность</h2>
<ul>
<li>Доступ к данным имеют только сотрудники, которым он необходим для работы.</li>
<li>Доступ к документам клиентов фиксируется в журнале.</li>
<li>Передача данных по сети защищена шифрованием.</li>
<li>Выполняется резервное копирование.</li>
</ul>

<h2>7. Передача третьим лицам</h2>
<p>Персональные данные не продаются и не передаются третьим лицам, за
исключением случаев, когда это необходимо для исполнения договора
(например, направление документов в суд или экспертную организацию) либо
предусмотрено законом.</p>

<h2>8. Права субъекта персональных данных</h2>
<p>Субъект вправе получить сведения об обработке своих данных, потребовать
их уточнения, блокирования или уничтожения, а также отозвать согласие.
Для этого достаточно направить обращение на контактный адрес оператора.</p>

<h2>9. Сроки хранения</h2>
<p>Данные хранятся в течение срока, необходимого для целей обработки, и
уничтожаются при достижении целей либо при отзыве согласия, если иное не
предусмотрено законом. <b>Конкретные сроки должен определить юрист.</b></p>

<h2>10. Изменения политики</h2>
<p>Оператор вправе изменять настоящую политику. Действующая редакция всегда
размещена на этой странице.</p>
"""


def consent_html(data: Content) -> str:
    return REVIEW_BANNER + _operator(data) + """
<p>Отправляя форму на сайте, я даю согласие на обработку моих персональных
данных на следующих условиях.</p>

<h2>Какие данные я предоставляю</h2>
<p>Имя, номер телефона, адрес электронной почты (если указан), название
объекта строительства и иные сведения, которые я сообщаю добровольно.</p>

<h2>Для чего они обрабатываются</h2>
<p>Для связи со мной, ответа на моё обращение, подготовки предварительного
расчёта и предложения услуг, а в случае заключения договора — для его
исполнения.</p>

<h2>Какие действия с данными разрешены</h2>
<p>Сбор, запись, систематизация, накопление, хранение, уточнение, извлечение,
использование, блокирование, удаление и уничтожение.</p>

<h2>Срок действия и отзыв</h2>
<p>Согласие действует до достижения целей обработки либо до его отзыва.
Отозвать согласие можно в любой момент, направив обращение на контактный
адрес оператора, указанный выше.</p>

<p>Я подтверждаю, что ознакомлен с <a href="/politika">политикой обработки
персональных данных</a>.</p>
"""
